import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { generateTokenCss } from '@edrion/design-tokens/css';

/**
 * Writes design-token CSS variables (including student theme blocks) to a static file
 * imported by globals.css. Run on predev/prebuild so variables match @edrion/design-tokens.
 */
const __dirname = dirname(fileURLToPath(import.meta.url));
const out = join(__dirname, '..', 'src', 'styles', 'tokens.css');
mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, `/* GENERATED by scripts/gen-tokens.ts — do not edit. */\n${generateTokenCss()}`);
// eslint-disable-next-line no-console
console.log(`✓ tokens.css written (${out})`);
